#!/bin/sh
# Compiles the firmware and embeds the .hex in editor/firmware.js, so that the
# editor can install it without the Arduino IDE.
# Needs arduino-cli with the arduino:avr core and the "Adafruit NeoPixel" and "Servo" libraries.
# Usage: tools/build_firmware.sh [arduino-cli arguments, e.g. --config-file cfg.yaml]
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
out=$(mktemp -d)
arduino-cli "$@" compile -b arduino:avr:uno --output-dir "$out" "$root/firmware/AdeeptBlocs"
{
  echo "// Generated by tools/build_firmware.sh: do not edit by hand."
  printf 'const FIRMWARE_HEX = `'
  cat "$out/AdeeptBlocs.ino.hex"
  echo '`;'
} > "$root/editor/firmware.js"
cp "$out/AdeeptBlocs.ino.hex" "$root/firmware/AdeeptBlocs.hex"
rm -rf "$out"
echo "editor/firmware.js and firmware/AdeeptBlocs.hex updated"
