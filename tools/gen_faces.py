def eye_bytes(rows, offset):
    out = []
    for r in rows:
        assert len(r) == 16, r
        b = 0
        for c in range(8):
            if r[offset + c] == "X":
                b |= 0x80 >> c
        out.append(b)
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = [
        "// Generated by tools/gen_faces.py: do not edit by hand.",
        "#pragma once",
        "#include <avr/pgmspace.h>",
        "",
        "#define NUM_FACES %d" % len(FACES),
        "",
        "// Per face: 8 rows of the left eye then 8 rows of the right eye (MSB = leftmost).",
        "static const uint8_t FACES[NUM_FACES][16] PROGMEM = {",
    ]
    for i, (name, rows) in enumerate(FACES):
        bs = eye_bytes(rows, 0) + eye_bytes(rows, 8)
        lines.append("  {%s},  // %d %s" % (", ".join("0x%02X" % b for b in bs), i, name))
    lines.append("};")
    with open(os.path.join(root, "firmware", "AdeeptBlocs", "faces.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    js = {name: rows for name, rows in FACES}
    with open(os.path.join(root, "editor", "faces.js"), "w") as f:
        f.write("// Generated by tools/gen_faces.py: do not edit by hand.\n")
        f.write("const FACE_NAMES = %s;\n" % json.dumps([n for n, _ in FACES]))
        f.write("const FACES = %s;\n" % json.dumps(js, indent=1))


main()
